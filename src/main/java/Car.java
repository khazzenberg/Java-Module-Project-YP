public class Car {
    //Название автомобиля
    String name;
    //Скорость автомобиля
    int speed;

    //Конструктор, который в качестве аргументов принимает
    //название (name) и скорость (speed)
    public Car(String name, int speed) {
        this.name = name;
        this.speed = speed;
    }
}
